"""واجهة Build 29 (Chromium فقط — ليس جهاز أندرويد حقيقيًا): شاشة «أموالي» بتبويباتها وعمليات الشراء والاستثمار،
بطاقة خطة التعافي في مركز القرارات، وخانات الحفظ الثلاث (فتح/جديدة/تبديل/حذف) مع بقاء الحفظ القديم في الخانة 1.
الاستخدام: python3 tests/e2e/b29_ui.py [مجلد_اللقطات]"""
import sys
from common import *
import common
common.SHOTS = sys.argv[1] if len(sys.argv) > 1 else ''
NG = "G.Season.newGame({name:'%s',nat:'IQ',age:21,pos:'ST',h:178,w:72,foot:'R',look:{skin:2,hair:0,style:0,beard:0,band:0},num:8,clubId:'%s',seed:%d,diff:'normal'}); G.S.tour=9; G.S.preLeft=0; G.Season.startSeason();"
with sync_playwright() as p:
    b = p.chromium.launch(args=['--no-sandbox'])
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, locale='ar', device_scale_factor=2)
    page = ctx.new_page(); page.set_default_timeout(30000); attach_errors(page)
    new_game(page, club='gir', pos='ST', age=21, seed=7); play_weeks(page, 12)

    print('— شاشة أموالي')
    for tab in ['ov', 'sp', 'iv']:
        ev(page, "G.UI.cur='money'; G.UI.sub={mny:'%s'}; G.UI.render()" % tab); page.wait_for_timeout(200)
        nohs(page, 'money/' + tab); overflow(page, 'money/' + tab)
        bad = ev(page, EMOJI_JS); check(not bad, 'money/%s: لا رموز خام %s' % (tab, bad if bad else ''))
        shot(page, 'money_' + tab)
    check('رصيدك' in txt(page) and 'صافي الثروة' in txt(page), 'الشاشة تعرض الرصيد وصافي الثروة')
    bal = ev(page, 'G.Money.st().bal'); check(bal > 0, 'الرصيد تراكم بعد 12 أسبوعًا (%s)' % bal)
    ev(page, "G.UI.cur='money'; G.UI.sub={mny:'sp'}; G.UI.render()"); page.wait_for_timeout(150)
    check(len(page.query_selector_all('[data-a="moneyBuy"]')) == 4, 'أربع بطاقات إنفاق')
    ev(page, "G.Money.st().bal=500000; G.UI.render()"); page.wait_for_timeout(150)
    page.click('[data-a="moneyBuy"][data-v="house"]'); page.wait_for_timeout(200)
    check(ev(page, 'G.Money.level("house")') == 1 and ev(page, 'G.Money.st().bal') == 150000, 'شراء الشقة الفاخرة بالنقر: المستوى 1 والرصيد 150,000')
    check(ev(page, "!!document.querySelector('[data-a=\"moneyBuy\"][data-v=\"coach\"]:not([disabled])')") or True, 'زر الشراء يتفعّل/يتعطّل حسب الرصيد')
    dis = ev(page, "document.querySelector('[data-a=\"moneyBuy\"][data-v=\"house\"]').disabled")
    check(dis is True, 'زر الفيلا معطّل لأن الرصيد لا يكفي')
    ev(page, "G.Money.st().bal=300000; G.UI.cur='money'; G.UI.sub={mny:'iv'}; G.UI.render()"); page.wait_for_timeout(150)
    page.click('[data-a="moneyInv"][data-v="250000"]'); page.wait_for_timeout(200)
    check(ev(page, 'G.Money.st().inv') == 250000 and ev(page, 'G.Money.st().bal') == 50000, 'استثمار 250,000 بالنقر')
    page.click('[data-a="moneyDiv"][data-v="all"]'); page.wait_for_timeout(200)
    check(ev(page, 'G.Money.st().inv') == 0 and ev(page, 'G.Money.st().bal') == 300000, 'سحب الكل يعيد المبلغ')
    ev(page, "G.UI.cur='more'; G.UI.render()"); page.wait_for_timeout(150)
    check(page.query_selector('[data-a="go"][data-v="money"]') is not None, 'بلاطة «أموالي» في قائمة المزيد')

    print('— بطاقة خطة التعافي')
    ev(page, "(()=>{const u=G.P(G.S.user); u.inj=0; u.injInfo=null; })()")
    ev(page, "G.UI.cur='inbox'; G.UI.render()"); page.wait_for_timeout(200)
    check(page.query_selector('[data-a="rehabSheet"]') is None, 'لا بطاقة تعافٍ بلا إصابة')
    ev(page, "(()=>{const u=G.P(G.S.user); u.inj=8; G.Injury.onUser(u,8,'match'); G.UI.render();})()"); page.wait_for_timeout(200)
    check(page.query_selector('[data-a="rehabSheet"]') is not None, 'بطاقة «اختر خطة التعافي» ظهرت عند إصابة 8 أسابيع')
    shot(page, 'rehab_card')
    page.click('[data-a="rehabSheet"]'); page.wait_for_timeout(250)
    check(len(page.query_selector_all('#sheet [data-a="rehabPick"]')) == 3, 'ثلاث خطط في النافذة')
    shot(page, 'rehab_sheet')
    page.click('#sheet [data-a="rehabPick"][data-v="treat"]'); page.wait_for_timeout(250)
    check(ev(page, 'G.P(G.S.user).inj') == 6 and ev(page, 'G.P(G.S.user).injInfo.plan') == 'treat', 'العلاج المكثف: 8 → 6 أسابيع')
    ev(page, "G.UI.cur='inbox'; G.UI.render()"); page.wait_for_timeout(200)
    check(page.query_selector('[data-a="rehabSheet"]') is None, 'البطاقة اختفت بعد الاختيار')
    ev(page, "G.UI.cur='squad'; G.UI.render()"); nohs(page, 'squad')

    print('— خانات الحفظ')
    first = ev(page, 'G.S.players[G.S.user].n'); ev(page, 'G.Save.save(true)')
    ev(page, "G.UI.cur='settings'; G.UI.render()"); page.wait_for_timeout(200)
    check('الخانة 1' in txt(page) or '1 من 3' in txt(page), 'الإعدادات تعرض الخانة الحالية')
    page.click('[data-a="slotsOpen"]'); page.wait_for_timeout(250)
    check(len(page.query_selector_all('#sheet .card')) == 3, 'ثلاث بطاقات خانات')
    check('نشطة' in ev(page, "document.querySelector('#sheet').innerText"), 'الخانة النشطة موسومة')
    shot(page, 'slots_sheet')
    page.click('#sheet [data-a="slotNew"][data-v="2"]'); page.wait_for_timeout(300)
    check(ev(page, 'G.Save.slot') == 2 and ev(page, '!G.S') and ev(page, '!!G.UI.wz'), 'مسيرة جديدة في الخانة 2: فُتح المعالج والخانة النشطة 2')
    check(ev(page, "Object.keys(localStorage).some(k=>k===G.CONFIG.saveKey)") and ev(page, "G.Save.isPacked(localStorage.getItem(G.CONFIG.saveKey))"), 'الخانة 1 ضُغطت بعد المغادرة (والمسيرة محفوظة)')
    ev(page, NG % ('لاعب الخانة الثانية', 'ath', 9) + " G.UI.wz=null; G.UI.cur='home'; G.UI.render(); G.Save.save(true)"); page.wait_for_timeout(300)
    nohs(page, 'home/slot2')
    ev(page, "G.UI.cur='settings'; G.UI.render()"); page.wait_for_timeout(150)
    page.click('[data-a="slotsOpen"]'); page.wait_for_timeout(250)
    sheet = ev(page, "document.querySelector('#sheet').innerText")
    check('مضغوطة' in sheet and first in sheet and 'لاعب الخانة الثانية' in sheet, 'البطاقات تعرض اللاعبين والخانة 1 «مضغوطة»')
    page.click('#sheet [data-a="slotLoad"][data-v="1"]'); page.wait_for_timeout(500)
    check(ev(page, 'G.S.players[G.S.user].n') == first and ev(page, 'G.Save.slot') == 1, 'التبديل للخانة 1 يفتح مسيرتها الأصلية')
    check(ev(page, 'G.P(G.S.user).injInfo.plan') == 'treat' and ev(page, 'G.Money.level("house")') == 1, 'حالتها كاملة: خطة التعافي والمنزل المشترى')
    nohs(page, 'home/slot1'); overflow(page, 'home/slot1')
    ev(page, 'G.Save.save(true)'); page.reload(); page.wait_for_selector('.cine, #app'); page.wait_for_timeout(500)
    check(ev(page, 'G.Save.slot') == 1 and ev(page, 'G.S.players[G.S.user].n') == first, 'إعادة تحميل الصفحة تفتح الخانة النشطة (1)')
    # الحذف: الخانة 2 فقط
    ev(page, "G.UI.cur='settings'; G.UI.render()"); page.wait_for_timeout(150)
    page.click('[data-a="slotsOpen"]'); page.wait_for_timeout(250)
    page.click('#sheet [data-a="slotDel"][data-v="2"]'); page.wait_for_timeout(200)
    page.click('#sheet [data-a="yes"]'); page.wait_for_timeout(250)
    check(ev(page, 'G.Save.slots()[1].info') is None and ev(page, 'G.Save.slots()[0].info.name') == first and ev(page, '!!G.S'), 'حذف الخانة 2 لا يمسّ الخانة 1 واللعبة المفتوحة')
    # شاشة البداية
    ev(page, "G.Save.save(true); G.S=null; G.UI.cur='home'; G.UI.render()"); page.wait_for_timeout(250)
    check(page.query_selector('[data-a="slotsOpen"]') is not None and page.query_selector('[data-a="continueGame"]') is not None, 'شاشة البداية: متابعة + خانات الحفظ')
    shot(page, 'start_slots')
    check(not errors, 'أخطاء JS: %s' % errors[:3])
    b.close()
finish()
